import httpx

from vaultproxy import __version__
from vaultproxy.config import settings
from vaultproxy.masking import MaskingEngine
from vaultproxy.vault import RequestVault


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="vaultproxy",
        description="Local-first, OpenAI-compatible privacy proxy for LLM apps focused on Indian data",
    )
    subparsers = parser.add_subparsers(dest="command", help="Available subcommands")

    # 1. run
    run_parser = subparsers.add_parser("run", help="Start the VaultProxy server")
    run_parser.add_argument(
        "--host", default="127.0.0.1", help="Host to bind (default: 127.0.0.1)"
    )
    run_parser.add_argument(
        "--port", type=int, default=8000, help="Port to bind (default: 8000)"
    )
    run_parser.add_argument(
        "--upstream", default=None, help="Override UPSTREAM_BASE_URL"
    )
    run_parser.add_argument(
        "--strict", action="store_true", help="Enable STRICT_MODE"
    )
    run_parser.add_argument(
        "--workers", type=int, default=1, help="Number of worker processes (default: 1)"
    )

    # 2. init
    subparsers.add_parser(
        "init", help="Initialize a new .env file with a secure random token"
    )

    # 3. doctor
    doctor_parser = subparsers.add_parser(
        "doctor", help="Run system diagnostics and check configuration health"
    )
    doctor_parser.add_argument(
        "--port", type=int, default=8000, help="Port to verify (default: 8000)"
    )

    # 4. check
    check_parser = subparsers.add_parser(
        "check", help="Dry-run sensitive data detection on text or a file without an upstream call"
    )
    check_parser.add_argument("text", nargs="?", default=None, help="Text to scan and mask")
    check_parser.add_argument("--file", "-f", default=None, help="File path containing text to scan and mask")

    # 5. version
    subparsers.add_parser("version", help="Print VaultProxy version")

    return parser


def cmd_version() -> int:
    print(f"vaultproxy {__version__}")
    return 0


def cmd_init() -> int:
    env_path = Path(".env")
    if env_path.exists():
        print("[WARN] .env already exists; will not overwrite.")
        return 0

    token = secrets.token_urlsafe(32)
    template = f"""# VaultProxy Configuration
# Generated by `vaultproxy init`

# Profile: development (default, permissive local dev) or production (strict checks)
VAULT_PROFILE=development

# Authentication token (required in production; minimum 24 characters)
VAULT_AUTH_TOKEN={token}

# Upstream OpenAI-compatible API base URL
UPSTREAM_BASE_URL=https://api.openai.com/v1

# Upstream API key (passed to upstream in Authorization: Bearer header)
UPSTREAM_API_KEY=

# SLM (Small Language Model) backend for contextual NER: off (default), ollama, gemini
GEMMA_BACKEND=off
GEMMA_MODEL=gemma2:2b

# Fail-closed strict mode: returns 503 if SLM fails or input exceeds capacity
STRICT_MODE=false
"""
    env_path.write_text(template, encoding="utf-8")
    print(f"[PASS] Generated .env with a secure random token (path: {env_path.resolve()})")
    return 0


def cmd_check(args: argparse.Namespace) -> int:
    content: str = ""
    if args.file:
        file_path = Path(args.file)
        if not file_path.exists():
            print(f"[FAIL] File not found: {args.file}", file=sys.stderr)
            return 1
        content = file_path.read_text(encoding="utf-8")
    elif args.text:
        content = args.text
    elif not sys.stdin.isatty():
        content = sys.stdin.read()
    else:
        print("[FAIL] Please provide text to check or specify --file <path>.", file=sys.stderr)
        return 1

    vault = RequestVault()
    engine = MaskingEngine(vault)
    masked_text = engine.mask_text(content)
    counts = vault.type_counts

    print("=== VaultProxy Check (Dry Run) ===")
    if counts:
        entities_summary = ", ".join(f"{k}: {v}" for k, v in sorted(counts.items()))
        print(f"Detected entities ({sum(counts.values())} total): {entities_summary}")
    else:
        print("No sensitive entities detected.")

    print("\n--- Masked Output ---")
    print(masked_text)
    return 0


def _check_port_free(host: str, port: int) -> bool:
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as s:
        s.settimeout(0.5)
        try:
            s.bind((host, port))
            return True
        except OSError:
            return False


async def run_doctor(port: int = 8000) -> int:
    print("=== VaultProxy Doctor Diagnostics ===")
    all_ok = True

    # 1. Python version
    py_ver = f"{sys.version_info.major}.{sys.version_info.minor}.{sys.version_info.micro}"
    if sys.version_info >= (3, 10):
        print(f"[PASS] Python version: {py_ver}")
    else:
        print(f"[FAIL] Python version: {py_ver} (Python >= 3.10 required)")
        all_ok = False

    # 2. Port free
    if _check_port_free("127.0.0.1", port):
        print(f"[PASS] Port {port}: Free")
    else:
        print(f"[WARN] Port {port}: In use (Fix hint: free the port or specify --port <port>)")

    # 3. UPSTREAM_BASE_URL form & reachability
    upstream_url = settings.UPSTREAM_BASE_URL
    if upstream_url:
        parsed = urlparse(upstream_url)
        if parsed.scheme in ("http", "https") and parsed.netloc:
            print(f"[PASS] UPSTREAM_BASE_URL format: Valid ({upstream_url})")
            # Try a lightweight check GET {base}/models
            models_url = upstream_url.rstrip("/") + ("/models" if "v1" in upstream_url else "/v1/models")
            try:
                headers = {}
                if settings.UPSTREAM_API_KEY:
                    headers["Authorization"] = f"Bearer {settings.UPSTREAM_API_KEY}"
                async with httpx.AsyncClient(timeout=2.0) as client:
                    resp = await client.get(models_url, headers=headers)
                    if resp.status_code in (200, 401, 403):
                        print(f"[PASS] Upstream endpoint responds (status {resp.status_code})")
                    else:
                        print(f"[WARN] Upstream endpoint returned status {resp.status_code}")
            except Exception as e:
                print(f"[WARN] Upstream reachability probe failed: {type(e).__name__} (Fix hint: verify upstream is running)")
        else:
            print(f"[FAIL] UPSTREAM_BASE_URL format invalid: {upstream_url}")
            all_ok = False
    else:
        print("[WARN] UPSTREAM_BASE_URL is not set (Fix hint: set UPSTREAM_BASE_URL in .env)")

    # 4. Upstream key present (never printed)
    if settings.UPSTREAM_API_KEY:
        print("[PASS] UPSTREAM_API_KEY is configured (value withheld)")
    else:
        print("[INFO] UPSTREAM_API_KEY is not set (optional for mock/local upstreams)")

    # 5. Auth token
    token = settings.VAULT_AUTH_TOKEN
    is_prod = settings.VAULT_PROFILE.lower() == "production"
    if token:
        if len(token) >= 24:
            print(f"[PASS] VAULT_AUTH_TOKEN configured ({len(token)} chars)")
        else:
            print(f"[FAIL] VAULT_AUTH_TOKEN too short ({len(token)} chars; min 24 required)")
            all_ok = False
    else:
        if is_prod:
            print("[FAIL] VAULT_AUTH_TOKEN required in production profile (Fix hint: set VAULT_AUTH_TOKEN in .env)")
            all_ok = False
        else:
            print("[INFO] VAULT_AUTH_TOKEN not set (development profile allows unauthenticated access)")

    # 6. SLM reachable & model check
    backend = settings.GEMMA_BACKEND.lower()
    if backend == "off":
        print("[PASS] GEMMA_BACKEND=off (rules-only mode, offline)")
    elif backend == "ollama":
        ollama_url = settings.OLLAMA_URL.rstrip("/")
        try:
            t_start = time.perf_counter()
            async with httpx.AsyncClient(timeout=2.0) as client:
                resp = await client.get(f"{ollama_url}/api/tags")
                t_latency = (time.perf_counter() - t_start) * 1000.0
            if resp.status_code == 200:
                models = [m.get("name", "") for m in resp.json().get("models", [])]
                model_present = any(settings.GEMMA_MODEL in name for name in models)
                if model_present:
                    print(f"[PASS] Ollama reachable at {ollama_url}, model '{settings.GEMMA_MODEL}' installed (latency: {t_latency:.1f}ms)")
                else:
                    print(f"[WARN] Ollama reachable, but model '{settings.GEMMA_MODEL}' not found. (Fix hint: run 'ollama pull {settings.GEMMA_MODEL}')")
                
                # SLM concurrency and estimated throughput
                concurrency = getattr(settings, "GEMMA_CONCURRENCY_LIMIT", 4)
                latency_sec = max(t_latency / 1000.0, 0.05)
                est_throughput = concurrency / latency_sec
                print(f"[INFO] SLM concurrency limit: {concurrency} slots, estimated max throughput: {est_throughput:.1f} req/s")
                if settings.STRICT_MODE:
                    print("[WARN] STRICT_MODE is ON: incoming requests exceeding SLM throughput will be refused with 503.")
            else:
                print(f"[WARN] Ollama returned status {resp.status_code} at {ollama_url}")
        except Exception as e:
            print(f"[WARN] Ollama unreachable at {ollama_url}: {type(e).__name__} (Fix hint: start Ollama or set GEMMA_BACKEND=off)")
    elif backend == "gemini":
        if settings.GEMINI_API_KEY:
            print("[PASS] GEMINI_API_KEY configured (value withheld)")
        else:
            print("[FAIL] GEMINI_API_KEY not configured for GEMMA_BACKEND=gemini")
            all_ok = False
    else:
        print(f"[FAIL] Unknown GEMMA_BACKEND: {backend}")
        all_ok = False

    # 7. Production profile checks
    if is_prod:
        prod_issues = []
        if settings.DEMO_MODE:
            prod_issues.append("DEMO_MODE=true is forbidden in production.")
        placeholder_substrings = ["your_", "changeme", "example", "token_here", "1234567890"]
        if token and any(s in token.lower() for s in placeholder_substrings):
            prod_issues.append(f"VAULT_AUTH_TOKEN contains placeholder text: '{token[:8]}...'")
        if prod_issues:
            print("[FAIL] Production profile validation issues:")
            for issue in prod_issues:
                print(f"  - {issue}")
            all_ok = False
        else:
            print("[PASS] Production profile validation checks passed")

    print("--------------------------------------")
    if all_ok:
        print("Doctor Result: PASS (System ready for VaultProxy)")
        return 0
    else:
        print("Doctor Result: ISSUES FOUND (See fix hints above)")
        return 1


def cmd_doctor(args: argparse.Namespace) -> int:
    return asyncio.run(run_doctor(port=args.port))


def cmd_run(args: argparse.Namespace) -> int:
    import uvicorn

    if args.upstream:
        os.environ["UPSTREAM_BASE_URL"] = args.upstream
    if args.strict:
        os.environ["STRICT_MODE"] = "true"

    uvicorn.run(
        "vaultproxy.server:app",
        host=args.host,
        port=args.port,
        workers=args.workers,
    )
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)

    if not args.command:
        parser.print_help()
        return 0

    if args.command == "version":
        return cmd_version()
    elif args.command == "init":
        return cmd_init()
    elif args.command == "check":
        return cmd_check(args)
    elif args.command == "doctor":
        return cmd_doctor(args)
    elif args.command == "run":
        return cmd_run(args)
    else:
        parser.print_help()
        return 0


if __name__ == "__main__":
    sys.exit(main())
